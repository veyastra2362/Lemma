//! 键盘观察契约。
//!
//! 用途只有两个：
//! 1. 识别「双击 Ctrl」这个呼出动作；
//! 2. 感知「用户按了别的键」，用来复位双击状态机（Ctrl+C 之后立刻再来一下 Ctrl
//!    不应该被当成双击）。
//!
//! **只读**：不吞键、不改键、不注入、不记录按键内容、不写盘。
//! 回调里除了往 channel 塞一个枚举，什么也不做。

/// 我们关心的按键信号。故意做成平台无关的语义，而不是原始键码。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeySignal {
    /// 修饰键 Ctrl（左右不分）按下。
    ControlDown,
    /// 修饰键 Ctrl 松开。
    ControlUp,
    /// 其它任意键按下——只用于复位双击状态机，不区分是哪个键。
    Other,
}
